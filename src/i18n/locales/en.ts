/**
 * The shape every locale must fill.
 *
 * `en` is `as const`, which makes each value its own literal type — useful for
 * catching a typo'd key, useless as a contract for a translation. Widening the
 * leaves to `string` gives translators a type that demands the same keys and
 * says nothing about the words.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

export type TranslationSchema = Widen<typeof en>;
