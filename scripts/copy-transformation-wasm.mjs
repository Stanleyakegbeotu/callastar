import { copyFile, mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const packageRoot = dirname(require.resolve("@mediapipe/tasks-vision"));
const packageMetadata = JSON.parse(await readFile(join(packageRoot, "package.json"), "utf8"));
const source = join(packageRoot, "wasm");
const base = resolve("public/transformation/wasm");
const target = join(base, packageMetadata.version);
const files = (await readdir(source)).filter((name) => /\.(?:js|wasm)$/.test(name));

for (const required of ["vision_wasm_internal.js", "vision_wasm_internal.wasm", "vision_wasm_nosimd_internal.js", "vision_wasm_nosimd_internal.wasm"]) {
  if (!files.includes(required)) throw new Error(`MediaPipe package is missing ${required}`);
}

await mkdir(target, { recursive: true });
for (const file of files) await copyFile(join(source, file), join(target, file));
await writeFile(join(target, "manifest.json"), JSON.stringify({ package: "@mediapipe/tasks-vision", version: packageMetadata.version, files }, null, 2));
await writeFile(
  resolve("src/features/transformation/wasmAssetPath.generated.ts"),
  `// Generated by scripts/copy-transformation-wasm.mjs. Do not edit by hand.\nexport const transformationWasmBasePath = "/transformation/wasm/${packageMetadata.version}";\n`,
);
// Remove only files produced by the earlier unversioned copy step.
for (const file of [...files, "manifest.json"]) {
  await unlink(join(base, file)).catch((error) => {
    if (error.code !== "ENOENT") throw error;
  });
}
console.log(`Copied ${files.length} MediaPipe WASM assets from ${packageMetadata.version} to ${target}`);
